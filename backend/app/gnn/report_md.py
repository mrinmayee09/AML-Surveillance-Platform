"""R6: write the results tables (docs/GNN_RESULTS.md) straight from the run reports.

Every number in the document comes from the R2 / R3 / R4 JSON reports, so the
paper's tables can be regenerated rather than copied by hand.

    cd backend
    python -m app.gnn.report_md
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Dict, List, Optional

from app.core.config import PROJECT_ROOT
from app.gnn.r2 import DEFAULT_DATA_DIR

OUT = PROJECT_ROOT / "docs" / "GNN_RESULTS.md"
ORDER = [
    ("seed-only", "Gradient boosting - account's own features", "no graph"),
    ("seed+context", "Gradient boosting - own + neighbour + transfer aggregates", "hand-made graph features"),
    ("logistic", "Logistic regression - own + neighbour + transfer aggregates", "hand-made graph features"),
    ("plain", "A. GraphSAGE (plain, undirected)", "learned"),
    ("directed", "B. Directed GraphSAGE", "learned"),
    ("edge", "C. Edge-aware directed GraphSAGE", "learned"),
]
SHORT = {"seed-only": "GB own", "seed+context": "GB +context", "logistic": "LogReg +context",
         "plain": "A", "directed": "B", "edge": "C"}


def _latest(pattern: str, folder: Path) -> Optional[dict]:
    files = sorted(folder.glob(pattern), key=lambda p: p.stat().st_mtime)
    return json.loads(files[-1].read_text(encoding="utf-8")) if files else None


def _ms(stat, pct: bool = False, digits: int = 1) -> str:
    if not isinstance(stat, dict) or "mean" not in stat:
        return "-"
    k = 100 if pct else 1
    fmt = f"{{:.{digits}f}}%" if pct else "{:.3f}"
    return f"{fmt.format(stat['mean'] * k)} ± {fmt.format(stat['std'] * k)}"


def build(folder: Path = DEFAULT_DATA_DIR / "r2") -> str:
    r2 = _latest("r2_report-*.json", folder)
    r3 = _latest("r3_report-*.json", folder)
    r4 = _latest("r4_report-*.json", folder)
    base = r2 or r3
    if base is None:
        raise SystemExit(f"no R2 or R3 report in {folder}")

    results: Dict[str, dict] = dict(r2["results"]) if r2 else {}
    if r3:
        results.update({k: v for k, v in r3["results"].items() if k in ("plain", "directed", "edge")})
    if "directed" not in results and "gnn" in results:
        results["directed"] = results["gnn"]

    ds = base["dataset"]
    lines: List[str] = [
        "# Reactive GNN - results on IBM AMLworld",
        "",
        "_Generated by `python -m app.gnn.report_md` from the run reports. Do not edit by hand._",
        "",
        "## Data and protocol",
        "",
        f"- **Dataset:** IBM AMLworld `{ds['file']}` (Altman et al., NeurIPS 2023): "
        f"{ds['transfers']:,} transfers between {ds['accounts']:,} accounts at {ds['banks']:,} banks, "
        f"{ds['laundering_transfers']:,} labelled laundering ({ds['laundering_rate']:.3%}).",
        f"- **Cut-off:** {'; '.join(ds.get('notes') or ['none'])}.",
        "- **Split by time:** "
        + ", ".join(f"{s['name']} {s['start'][:10]} → {s['end'][:10]} ({s['days']} days, "
                    f"{s['transfers']:,} transfers, {s['laundering']:,} laundering)" for s in base["splits"])
        + ".",
        "- **Task:** for each account active on a day, predict whether it sent or received a "
        "laundering transfer that day, from its 7-day, 3-hop neighbourhood (capped at 300 accounts).",
        "- **Sampling:** all positive accounts kept; negatives sampled (1% train, 2% val/test) and "
        "re-weighted, so precision, PR-AUC and alert rate estimate the result on *all* active accounts.",
        f"- **Windows:** " + ", ".join(f"{k} {v['count']:,} ({v['positives']:,} positive)"
                                       for k, v in (r2 or {}).get("windows", {}).items())
        + ".",
        "- **Training:** AdamW, up to 30 epochs, early stopping on validation PR-AUC (patience 5) "
        "after a 10-epoch warm-up, so a slow-starting run is not cut off before it learns.",
        "- **Thresholds** chosen on validation (max F1), applied unchanged to test. "
        f"**{base['config']['seeds']} seed(s)** per stochastic model (mean ± std).",
        "",
        "## Main results (test split)",
        "",
        f"Estimated base rate: **{next(iter(results.values()))['test']['base_rate']['mean']:.2%}** of active "
        "accounts launder on a given day - a model flagging at random has PR-AUC ≈ base rate.",
        "",
        "| Model | Uses the graph | PR-AUC | Precision | Recall | F1 | Alert rate |",
        "|---|---|---|---|---|---|---|",
    ]
    for key, label, kind in ORDER:
        if key not in results:
            continue
        t = results[key]["test"]
        lines.append(
            f"| {label} | {kind} | {_ms(t.get('pr_auc'))} | {_ms(t.get('precision'))} | "
            f"{_ms(t.get('recall'))} | {_ms(t.get('f1'))} | {_ms(t.get('alert_rate'), True)} |"
        )

    lines += ["", "## Validation PR-AUC (used for model selection)", "", "| Model | Val PR-AUC |", "|---|---|"]
    for key, label, _ in ORDER:
        if key in results:
            lines.append(f"| {label} | {_ms(results[key]['val'].get('pr_auc'))} |")
    if r3:
        sel = r3["selected"]
        lines += ["", f"**Selected for the app:** {dict((k, l) for k, l, _ in ORDER)[sel['variant']]} - {sel['rule']}."]

    lines += ["", "## Recall by laundering pattern (test split)", ""]
    keys = [k for k, *_ in ORDER if k in results and "recall_by_typology" in results[k]["test"]]
    typos = sorted({t for k in keys for t in results[k]["test"]["recall_by_typology"]})
    if typos:
        lines.append("| Pattern | Accounts | " + " | ".join(SHORT[k] for k in keys) + " |")
        lines.append("|---|---|" + "---|" * len(keys))
        for t in typos:
            support = max(results[k]["test"]["recall_by_typology"].get(t, {}).get("support", 0) for k in keys)
            cells = [f"{results[k]['test']['recall_by_typology'][t]['mean']:.2f}"
                     if t in results[k]["test"]["recall_by_typology"] else "-" for k in keys]
            lines.append(f"| {t} | {support} | " + " | ".join(cells) + " |")
        lines.append("")
        lines.append("_Laundering transfers not listed in the patterns file count toward overall recall but "
                     "appear in no row here._")

    if r4:
        lines += ["", "## Explanation fidelity (R4)", "",
                  "Remove the transfers an explanation names, versus the same number of random nearby "
                  "transfers, and measure how much the flagged account's score falls.", "",
                  "| k | Flagged test accounts | Score drop: top-k | Score drop: random k | Top-k larger | Un-flags: top-k | Un-flags: random |",
                  "|---|---|---|---|---|---|---|"]
        for name, res in r4["results"].items():
            a = res["all_flagged"]
            if a.get("windows"):
                lines.append(
                    f"| {res['k']} | {a['windows']} | {a['mean_top_k_drop']:.3f} | {a['mean_random_k_drop']:.3f} | "
                    f"{a['top_beats_random']:.0%} | {a['top_k_flip_rate']:.0%} | {a['random_k_flip_rate']:.0%} |"
                )
    return "\n".join(lines) + "\n"


def main() -> None:
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(build(), encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
